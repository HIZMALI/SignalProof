import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const names = ["react", "react-dom", "scheduler", "lucide-react", "@js-temporal/polyfill", "jsbi", "tailwindcss", "vite", "rolldown"];
const sections = ["SignalProof — third-party notices\n\nThese notices cover runtime packages, generated CSS and bundler helpers.\nThey do not grant a license to SignalProof's original project source.\nGenerated from installed packages matching package-lock.json.\n"];
for (const name of names) {
  const folder = join("node_modules", name);
  const metadata = JSON.parse(await readFile(join(folder, "package.json"), "utf8"));
  const files = (await readdir(folder)).filter((file) => /^(?:licen[sc]e|copying|notice)(?:\.|$)/i.test(file));
  if (!files.length) throw new Error(`Missing notice for ${name}`);
  sections.push(`\n${"=".repeat(72)}\n${name} ${metadata.version} — ${metadata.license}\nhttps://www.npmjs.com/package/${name}/v/${metadata.version}\n`);
  for (const file of files.sort()) sections.push(`\n${file}\n\n${await readFile(join(folder, file), "utf8")}`);
}
const lock = JSON.parse(await readFile("package-lock.json", "utf8"));
const rows = Object.entries(lock.packages).filter(([path]) => path).map(([path, info]) => {
  if (!info.license) throw new Error(`Unspecified dependency license: ${path}`);
  const name = path.split("node_modules/").at(-1);
  return `| ${name} | ${info.version} | ${info.license} | ${info.dev ? "Development / build / test" : "Runtime or peer/type dependency"} |`;
});
const inventory = "# Locked dependency license inventory\n\nGenerated by `npm run notices:generate` from `package-lock.json`. Includes optional platform packages, which may not be installed locally. Package metadata labels are an inventory, not a replacement for actual license terms. Full shipped-code notices are in [third-party-notices.txt](../public/third-party-notices.txt); see [attribution context](THIRD-PARTY.md). No license for SignalProof's original code is selected by this file.\n\n| Package | Locked version | Declared license | Use |\n| --- | --- | --- | --- |\n" + rows.join("\n") + "\n";
// Normalize line endings/trailing whitespace; preserve every notice's wording.
const notices = sections.join("\n").replaceAll("\r\n", "\n").replace(/[ \t]+$/gm, "").trimEnd() + "\n";
for (const [path, content] of [["public/third-party-notices.txt", notices], ["docs/DEPENDENCY-LICENSES.md", inventory]]) {
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")).replaceAll("\r\n", "\n") !== content) throw new Error(`Stale dependency notices: ${path}`);
  } else await writeFile(path, content);
}
console.log(`${process.argv.includes("--check") ? "Verified" : "Updated"} nine shipped-code notices and ${rows.length} locked dependency entries. No project license selected.`);
